🧪 اختبر Backend الآن
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

1️⃣  تحقق من أن Backend يعمل:
   http://localhost:5000

2️⃣  سجّل مستخدم جديد:
   curl -X POST http://localhost:5000/auth/register \
     -H "Content-Type: application/json" \
     -d '{"institution_name":"My School","email":"student@test.com","password":"pass123","role":"student","full_name":"Test"}'

3️⃣  سجّل الدخول:
   curl -X POST http://localhost:5000/auth/login \
     -H "Content-Type: application/json" \
     -d '{"email":"student@test.com","password":"pass123","user_type":"student"}'

4️⃣  استخدم التوكن المُرجع في الطلبات الأخرى:
   curl -H "Authorization: Bearer YOUR_TOKEN_HERE" http://localhost:5000/api/endpoint


